def fail(message):
    sys.exit(f"make_cases: {message}")


def code_lines(text):
    """Batch lines that are not comments; FuSION 1 comments start with ';'."""
    return [line for line in text.splitlines() if not line.lstrip().startswith(";")]


def check_covered(case_id, texts, path_map):
    """Every absolute path a batch or list file names must fall under the path map."""
    froms = [entry["from"] for entry in path_map]
    for text in texts:
        for path in ABSOLUTE.findall("\n".join(code_lines(text))):
            if not any(path == f or path.startswith(f + "/") for f in froms):
                fail(f"{case_id}: {path} is not covered by its path map")


def used_maps(texts, candidates):
    joined = "\n".join("\n".join(code_lines(t)) for t in texts)
    return [{"from": f, "to": t} for f, t in candidates if f in joined]


def solve_artefacts(run_dir, prefix, required):
    """The solve cases of a FuSION 1 output folder, keyed by section 06's case names.

    A run that stopped before its solves has none; that is allowed only for a
    regenerated case (one toy run of 2025 stopped with empty up and down lists).
    """
    solve = {}
    for dat in sorted(run_dir.glob("*.dat")):
        m = re.match(r"^.+?_to_.+?_(w|wo)_(.+)_b\d+\.dat$", dat.name)
        if not m:
            fail(f"{dat}: unexpected .dat name")
        arm, rest = m.groups()
        case = "free" if rest.startswith("target_only_") else {"w": "in", "wo": "out"}[arm]
        if case in solve:
            fail(f"{run_dir}: two .dat files for the {case} case")
        stem = dat.name[:-len(".dat")]
        limits = run_dir / f"{stem}_limits_timefile.txt"
        if not limits.exists():
            fail(f"{limits} is missing")
        entry = {"dat": prefix + dat.name, "limits": prefix + limits.name}
        for kind in ("solutions", "relaxations"):
            path = run_dir / f"temp_{arm}_{kind}.txt"
            if path.exists():
                entry[kind] = prefix + path.name
        entry["arm"] = arm
        solve[case] = entry
    if not solve and required:
        fail(f"{run_dir}: no .dat files")
    return solve


def seconds(run_dir, solve, batch_text):
    """FuSION 1's pathz3 time per solve case, from timing.log."""
    log = run_dir / "timing.log"
    if not log.exists():
        return {}
    text = log.read_text(errors="replace")
    if "phase 1" in text and not re.search(r"phase 1 : start[^\n]*\n[^\n]*timing_w_start", batch_text):
        fail(f"{run_dir}: 'phase 1' is not the with-FSC solve in its batch")
    by_arm = {}
    for label, value in TIMING.findall(text):
        by_arm[ARM_OF_LABEL[label]] = float(value)
    return {case: by_arm[e["arm"]] for case, e in solve.items() if e["arm"] in by_arm}


def started(run_dir):
    log = run_dir / "timing.log"
    m = START.search(log.read_text(errors="replace")) if log.exists() else None
    if not m:
        return None
    month, day, year = m.groups()
    return f"{year}-{MONTHS[month]:02d}-{int(day):02d}"


def fusion1_block(run_dir, prefix, console, required=True):
    solve = solve_artefacts(run_dir, prefix, required)
    gsea = (run_dir / "gsea_kgml_files.gsea.tsv").exists()
    block = {
        "up": prefix + "up_reg",
        "down": prefix + "down_reg",
        "exceptions": prefix + "exception_file.txt",
        "console": console,
    }
    if gsea:
        block["gsea_table"] = prefix + "gsea_kgml_files.gsea.tsv"
        block["shortlist"] = prefix + "gsea_kgml_files.txt"
    block["reread"] = "f1/capture/graph_reread.xml"
    block["corridor"] = "f1/capture/corridor.xml"
    block["solve"] = solve
    return block


def finish(entry, solve_seconds):
    for e in entry["fusion1"]["solve"].values():
        del e["arm"]
    entry["fusion1_seconds"] = {k: round(v, 3) for k, v in sorted(solve_seconds.items())}
    return entry


def recorded_cases(root):
    cases = []
    for case_id, folder, tier in RECORDED:
        d = root / "runs" / folder
        batches = sorted(d.glob("*.batch"))
        if len(batches) != 1:
            fail(f"{d}: expected one batch file, found {len(batches)}")
        batch = batches[0]
        run_dir = d / "run"
        batch_text = batch.read_text(errors="replace")
        lists = [p.read_text(errors="replace") for p in sorted((d / "inputs").glob("*list*"))]
        path_map = [{"from": f"{FUSION}/runs/{folder}", "to": "$CASE"}]
        path_map += used_maps([batch_text] + lists, [KGML, UPDATED, SUPPORT])
        check_covered(case_id, [batch_text] + lists, path_map)
        for name in ("up_reg", "down_reg", "exception_file.txt"):
            if not (run_dir / name).exists():
                fail(f"{run_dir / name} is missing")
        if (d / "run_console.log").exists():
            console = "f1/run_console.log"
        elif (d / "run.log").exists():
            console = "f1/run.log"
        else:
            fail(f"{d}: no console log")
        block = fusion1_block(run_dir, "f1/run/", console)
        date = started(run_dir)
        if not date:
            fail(f"{run_dir}: no start time in timing.log")
        entry = {
            "id": case_id,
            "batch": f"fusion1-batches/runs/{folder}/{batch.name}",
            "tier": tier,
            "source": f"recorded {date}",
            "origin": {"batch": f"runs/{folder}/{batch.name}", "outputs": f"runs/{folder}",
                       "inputs": f"runs/{folder}/inputs"},
            "path_map": path_map,
            "fusion1": block,
        }
        cases.append(finish(entry, seconds(run_dir, block["solve"], batch_text)))
    return cases


def regenerated_dir(data_root, case_id, synthetic):
    """W4's output folder for a regenerated case, if W4 has run."""
    if synthetic:
        d = Path(__file__).resolve().parents[2] / "reference" / "synthetic" / case_id / "f1" / "run"
    elif data_root:
        d = data_root / "reference" / case_id / "f1" / "run"
    else:
        return None
    return d if d.is_dir() else None


def regenerated_entry(case_id, tier, batch_rel, origin, path_map, old_run_dir, batch_text, data_root,
                      synthetic=False):
    new_dir = regenerated_dir(data_root, case_id, synthetic)
    run_dir = new_dir or old_run_dir
    block = fusion1_block(run_dir, "f1/run/", "f1/run_console.log", required=False)
    entry = {
        "id": case_id,
        "batch": batch_rel,
        "tier": tier,
        "source": "regenerated" if new_dir else "regenerated (pending: artefacts from the recorded outputs)",
        "origin": origin,
        "path_map": path_map,
        "fusion1": block,
    }
    return finish(entry, seconds(run_dir, block["solve"], batch_text))


def egf_hela_cases(root, data_root):
    cases = []
    for fsc in EGF_FSCS:
        for setting in EGF_SETTINGS:
            stem = f"egfr_to_il8_fsc_{fsc}_b6_t700_f800_{setting}"
            rel = f"runs/egf_hela/experiment/{stem}.batch"
            batch_text = (root / rel).read_text(errors="replace")
            case_id = f"egfhela-{fsc}-b6-{setting.replace('_', '-')}"
            path_map = used_maps([batch_text], EGF_HELA)
            check_covered(case_id, [batch_text], path_map)
            origin = {"batch": rel, "outputs": f"runs/egf_hela/experiment/{stem}"}
            cases.append(regenerated_entry(case_id, "T2", f"fusion1-batches/{rel}", origin, path_map,
                                           root / origin["outputs"], batch_text, data_root))
    return cases


def model_case(root, data_root):
    rel = "macOS/model_example/run_model_example.batch"
    batch_text = (root / rel).read_text(errors="replace")
    if MODEL_PLACEHOLDER not in "\n".join(code_lines(batch_text)):
        fail(f"{rel}: the $WORK_DIR placeholder has changed")
    path_map = [{"from": MODEL_PLACEHOLDER, "to": "$CASE"}]
    check_covered("model-example", [batch_text], path_map)
    origin = {"batch": rel, "outputs": "macOS/model_example/run", "inputs": "macOS/model_example/inputs"}
    return regenerated_entry("model-example", "T2", f"fusion1-batches/{rel}", origin, path_map,
                             root / origin["outputs"], batch_text, data_root)


def toy_cases(root):
    cases = []
    for d in sorted((root / TOY_DIR).iterdir()):
        m = re.match(r"^hsa1_to_hsa22_fsc_(hsa\d+)_(report_example|with_node_included)\.(tsv|csv)_b(\d+)$",
                     d.name)
        if not m:
            fail(f"{d}: unexpected toy folder name")
        fsc, values, ext, bound = m.groups()
        listed = (d / "list_of_xml_files_new.txt").read_text().split()
        if len(listed) != 1:
            fail(f"{d}: expected one network in list_of_xml_files_new.txt")
        network = Path(listed[0]).name
        case_id = f"toy-{fsc}-{'report' if values == 'report_example' else 'wni'}-{ext}-b{bound}"
        origin = {"outputs": f"{TOY_DIR}/{d.name}", "network": f"example/{network}",
                  "values": f"example/{values}.{ext}", "fsc": fsc, "bound": int(bound)}
        path_map = [{"from": TOY_ROOT, "to": "$CASE"}]
        cases.append(regenerated_entry(case_id, "T1", f"toy-batches/{case_id}.batch", origin, path_map,
                                       d, "", None, synthetic=True))
    if len(cases) != 12:
        fail(f"expected 12 toy cases, found {len(cases)}")
    return cases


def main():
    if len(sys.argv) not in (3, 4):
        fail("usage: make_cases.py FUSION1_ROOT OUT_JSON [DATA_ROOT]")
    root = Path(sys.argv[1])
    out = Path(sys.argv[2])
    data_root = Path(sys.argv[3]) if len(sys.argv) == 4 else None
    cases = toy_cases(root) + egf_hela_cases(root, data_root) + [model_case(root, data_root)]
    cases += recorded_cases(root)
    ids = [c["id"] for c in cases]
    if len(set(ids)) != len(ids):
        fail("duplicate case ids")
    tiers = {t: sum(c["tier"] == t for c in cases) for t in ("T1", "T2", "T3")}
    if tiers != {"T1": 12, "T2": 23, "T3": 16}:
        fail(f"tier counts {tiers}, expected 12, 23 and 16 (section 12)")
    document = {
        "schema": 1,
        "generated_by": "backend/tests/experiments/capture/make_cases.py",
        "cases": cases,
    }
    out.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out}: {len(cases)} cases, {tiers}")


if __name__ == "__main__":
    main()
